local builtin = require('telescope.builtin')
vim.keymap.set('n', '<leader>pf', builtin.find_files, { desc = 'Find files' })
vim.keymap.set('n', '<leader>g', builtin.git_files, { desc = 'Git files' })
vim.keymap.set('n', '<leader>ps', function()
	builtin.grep_string({ search = vim.fn.input("Grep > ") })
end, { desc = 'Grep for string' })
vim.keymap.set('n', '<leader>pg', builtin.live_grep, { desc = 'Live grep' })
vim.keymap.set('n', '<leader>pb', builtin.buffers, { desc = 'Open buffers' })
vim.keymap.set('n', '<leader>pr', builtin.oldfiles, { desc = 'Recent files' })
vim.keymap.set('n', '<leader>pd', builtin.diagnostics, { desc = 'Diagnostics' })
vim.keymap.set('n', '<leader>po', builtin.lsp_document_symbols, { desc = 'Symbols in file' })
vim.keymap.set('n', '<leader>pk', builtin.keymaps, { desc = 'Search keymaps' })
